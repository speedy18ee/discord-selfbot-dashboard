async function checkAndUseLicense(keyToTest, clientHwid) {
  const cleanKey = (keyToTest || '').trim().toUpperCase();
  if (!cleanKey) {
    return { valid: false, error: 'Please enter a license key.' };
  }
  if (cleanKey.includes('RED') || cleanKey === 'RED EXE') {
    return {
      valid: false,
      error: 'Invalid entry. Please enter a valid license key generated by our Discord Bot (type "key" in Discord).'
    };
  }

  // Look up key from MariaDB (with instant file fallback)
  const found = await db.getLicense(cleanKey);

  if (!found) {
    return {
      valid: false,
      error: 'Invalid license key. Only keys generated by our Discord Bot are allowed! Type "key" or "getkey" in our Discord server.'
    };
  }

  // 1-Device HWID Lock Protocol
  const effectiveHwid = (clientHwid || '').trim();
  if (found.hwid && effectiveHwid && found.hwid !== effectiveHwid) {
    console.warn(`[SPY WEB] 🔒 HWID Lock violation on key ${found.key}! Locked to: ${found.hwid}, Attempted: ${effectiveHwid}`);
    return {
      valid: false,
      hwidMismatch: true,
      error: `🔒 HWID Lock Violation: This license key is locked to 1 device only. Ask the bot owner (User ID: 1527609131043917874) to reset your HWID by typing "resethwid ${found.key}" in Discord.`
    };
  }

  // First time login from this device: bind HWID permanently
  if (!found.hwid && effectiveHwid) {
    found.hwid = effectiveHwid;
    await db.updateHwidLock(found.key, effectiveHwid);
    console.log(`[SPY WEB] 🔒 HWID Lock: Key ${found.key} successfully locked to device: ${effectiveHwid}`);
  }

  const tier = found.tier || (found.maxAccounts > 4 ? 'premium' : 'standard');
  const maxAccounts = found.maxAccounts || (tier === 'premium' ? 30 : 4);

  return { valid: true, key: found.key, tier, maxAccounts, hwid: found.hwid };
}

// --- Discord REST API Helper ---
function discordRequest(endpoint, token, method = 'GET', body = null) {
  return new Promise((resolve, reject) => {
    const cleanToken = (token || '').trim().replace(/['"]/g, '');
    const isBot = cleanToken.startsWith('Bot ');
    const authHeader = isBot ? cleanToken : cleanToken.replace(/^Bot\s+/i, '');

    const bodyPayload = body ? (typeof body === 'string' ? body : JSON.stringify(body)) : null;

    const headers = {
      'Authorization': authHeader,
      'Content-Type': 'application/json',
      'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36'
    };

    if (bodyPayload) {
      headers['Content-Length'] = Buffer.byteLength(bodyPayload);
    }

    const req = https.request({
      hostname: 'discord.com',
      port: 443,
      path: `/api/v9${endpoint}`,
      method,
      headers
    }, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try {
          const parsed = JSON.parse(data);
          if (res.statusCode >= 200 && res.statusCode < 300) {
            resolve(parsed);
          } else {
            const errDetail = parsed.message || (typeof parsed === 'object' ? JSON.stringify(parsed) : parsed);
            reject(new Error(errDetail || `Discord API error ${res.statusCode}`));
          }
        } catch (e) {
          if (res.statusCode >= 200 && res.statusCode < 300) {
            resolve(data);
          } else {
            reject(new Error(`Discord API error ${res.statusCode}: ${data}`));
          }
        }
      });
    });

    req.on('error', reject);
    if (bodyPayload) req.write(bodyPayload);
    req.end();
  });
}

