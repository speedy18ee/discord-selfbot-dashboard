  // --- Dedicated Multi-Account Audio Player & Voice Pipeline ---
  function playTrackForPlayer(player, filePath, volumeMultiplier = 1.0) {
    try {
      if (!fs.existsSync(filePath)) return false;
      const resource = createAudioResource(filePath, { inlineVolume: true });
      if (resource.volume) {
        resource.volume.setVolume(Math.max(0.1, Math.min(volumeMultiplier, 10.0)));
      }
      player.play(resource);
      return true;
    } catch (e) {
      console.warn('[SPY WEB] Play stream error:', e.message);
      return false;
    }
  }

  function playTrackForOperative(op, filePath, volumeMultiplier = 1.0) {
    try {
      if (!fs.existsSync(filePath)) return false;
      if (op && op.player) {
        return playTrackForPlayer(op.player, filePath, volumeMultiplier);
      }
      return false;
    } catch (err) {
      console.warn('[SPY WEB] Operative audio play error:', err.message);
      return false;
    }
  }

  async function connectBotToVoice(guildId, channelId) {
    const botClient = getBotClient();
    if (!botClient || !botClient.isReady()) {
      console.warn('[SPY WEB] Discord Bot client is still connecting...');
      return false;
    }

    try {
      const guild = botClient.guilds.cache.get(guildId) || await botClient.guilds.fetch(guildId).catch(() => null);
      if (guild && guild.voiceAdapterCreator) {
        if (activeBotConnection) {
          try { activeBotConnection.destroy(); } catch (e) {}
          activeBotConnection = null;
        }

        activeBotConnection = joinVoiceChannel({
          channelId: channelId,
          guildId: guildId,
          adapterCreator: guild.voiceAdapterCreator,
          selfDeaf: false,
          selfMute: false
        });

        if (!activeBotPlayer) {
          activeBotPlayer = createAudioPlayer();
          activeBotPlayer.on(AudioPlayerStatus.Idle, () => {
            if (currentLoopTrack) {
              playTrackForPlayer(activeBotPlayer, currentLoopTrack.filePath, currentLoopTrack.volume);
            }
          });
          activeBotPlayer.on('error', err => {
            console.warn('[SPY WEB] Bot audio player note:', err.message);
          });
        }

        activeBotConnection.subscribe(activeBotPlayer);
        console.log(`[SPY WEB] ✓ SPY WEB Bot [${botClient.user.tag}] connected to voice channel ${channelId}`);
        return true;
      }
    } catch (err) {
      console.warn('[SPY WEB] Bot voice connection note:', err.message);
    }
    return false;
  }

  // Selfbot Voice Gateway Adapter (bridges @discordjs/voice with discord.js-selfbot-v13 gateway)
  function createSelfbotVoiceAdapter(guild) {
    return methods => {
      guild.client.voice.adapters.set(guild.id, methods);
      return {
        sendPayload: data => {
          try {
            const shard = guild.client.ws?.shards?.first() || guild.shard || guild.client.ws?.shards?.get(0);
            if (shard) {
              shard.send(data);
              return true;
            }
            if (guild.client.ws?.connection) {
              guild.client.ws.connection.send(JSON.stringify(data));
              return true;
            }
          } catch (e) {
            console.warn('[SPY WEB] Voice adapter sendPayload note:', e.message);
          }
          return false;
        },
        destroy: () => {
          guild.client.voice.adapters.delete(guild.id);
        }
      };
    };
  }

  async function connectUserToVoice(token, guildId, channelId) {
    const cleanToken = token.trim().replace(/['"]/g, '').replace(/^Bot\s+/i, '');
    let selfbot = activeSelfbotClients.get(cleanToken);
    if (!selfbot || !selfbot.isReady()) {
      console.log(`[SPY WEB] Authenticating operative account client...`);
      selfbot = new SelfbotClient({ checkUpdate: false });
      selfbot.on('error', err => console.warn('[SPY WEB Selfbot] Client error:', err?.message || err));
      selfbot.on('shardError', err => console.warn('[SPY WEB Selfbot] Shard error:', err?.message || err));
      try {
        await selfbot.login(cleanToken);
      } catch (loginErr) {
        console.error('[SPY WEB] Operative account login failed:', loginErr.message);
        throw new Error(loginErr.message.includes('token') ? 'Invalid or expired Discord token' : loginErr.message);
      }
      activeSelfbotClients.set(cleanToken, selfbot);
    }

    console.log(`[SPY WEB] Connecting operative [${selfbot.user?.tag}] to VC ${channelId}...`);

    // Auto-resolve guildId if not provided
    if (!guildId) {
      const ch = await selfbot.channels.fetch(channelId).catch(() => null);
      if (ch && ch.guildId) guildId = ch.guildId;
    }

    const guild = selfbot.guilds.cache.get(guildId) || await selfbot.guilds.fetch(guildId).catch(() => null);
    if (!guild) {
      throw new Error(`Account [${selfbot.user?.tag}] is not in guild ${guildId}`);
    }

    // Clean up previous connection for this token if any
    const existing = activeOperatives.get(cleanToken);
    if (existing) {
      try { existing.player?.stop(); } catch (e) {}
      try { existing.connection?.destroy(); } catch (e) {}
      activeOperatives.delete(cleanToken);
    }

    // Direct @discordjs/voice pipeline
    const connection = joinVoiceChannel({
      channelId: channelId,
      guildId: guildId,
      adapterCreator: createSelfbotVoiceAdapter(guild),
      selfDeaf: false,
      selfMute: false
    });

    const player = createAudioPlayer();
    connection.subscribe(player);

    player.on(AudioPlayerStatus.Idle, () => {
      if (currentLoopTrack) {
        playTrackForOperative(activeOperatives.get(cleanToken), currentLoopTrack.filePath, currentLoopTrack.volume);
      }
    });

    player.on('error', err => {
      console.warn(`[SPY WEB] Player error on operative [${selfbot.user?.tag}]:`, err.message);
    });

    connection.on(VoiceConnectionStatus.Ready, () => {
      console.log(`[SPY WEB] ✓ Operative [${selfbot.user?.tag}] VOICE READY in VC ${channelId}!`);
      connection.subscribe(player);
      if (currentLoopTrack) {
        playTrackForOperative(activeOperatives.get(cleanToken), currentLoopTrack.filePath, currentLoopTrack.volume);
      }
    });

    connection.on(VoiceConnectionStatus.Disconnected, async () => {
      try {
        await Promise.race([
          entersState(connection, VoiceConnectionStatus.Signalling, 5000),
          entersState(connection, VoiceConnectionStatus.Connecting, 5000)
        ]);
      } catch (e) {
        try { connection.destroy(); } catch (err) {}
        activeOperatives.delete(cleanToken);
      }
    });

    activeOperatives.set(cleanToken, {
      client: selfbot,
      connection,
      player,
      guildId,
      channelId,
      username: selfbot.user?.tag || selfbot.user?.username || 'Operative'
    });

    return true;
  }

  function playAudioTrack(filePath, volumeMultiplier = 1.0) {
    if (!fs.existsSync(filePath)) {
      console.warn(`[SPY WEB] Audio file not found on disk: ${filePath}`);
      return false;
    }

    let playedCount = 0;

    // 1. Play on all connected operative accounts
    for (const [token, op] of activeOperatives.entries()) {
      if (op && op.player) {
        const ok = playTrackForPlayer(op.player, filePath, volumeMultiplier);
        if (ok) playedCount++;
      }
    }

    // 2. Play on SPY WEB Bot if connected
    if (activeBotConnection && activeBotPlayer) {
      const botOk = playTrackForPlayer(activeBotPlayer, filePath, volumeMultiplier);
      if (botOk) playedCount++;
    }

    console.log(`[SPY WEB] 🎵 Playing sound resource: "${path.basename(filePath)}" (${volumeMultiplier.toFixed(2)}x) across ${playedCount} audio stream(s) (${activeOperatives.size} operatives, ${activeBotConnection ? 1 : 0} bot)!`);
    return playedCount > 0;
  }

  // 7. Join Voice Channel — ALL ACCOUNTS JOIN SIMULTANEOUSLY
  async function handleJoinVoice(data, callback) {
    let { guildId, channelId } = data || {};
    console.log(`[SPY WEB] 🔊 Connecting amplifier for license [${socket.activeLicenseKey}] to guild ${guildId || 'Auto'}, VC ${channelId}`);

    const userAccs = accounts.filter(a => a.licenseKey === socket.activeLicenseKey);

    // Auto-resolve guildId if missing
    if (!guildId && userAccs.length > 0) {
      for (const a of userAccs) {
        if (a.token) {
          try {
            const cleanT = a.token.trim().replace(/['"]/g, '').replace(/^Bot\s+/i, '');
            const ch = await discordRequest(`/channels/${channelId}`, cleanT);
            if (ch && ch.guild_id) {
              guildId = ch.guild_id;
              break;
            }
          } catch (e) {}
        }
      }
    }

    // Connect user accounts
    const results = [];
    for (const acc of userAccs) {
      if (!acc.token) {
        results.push({ success: false, username: acc.username, error: 'No token configured' });
        continue;
      }
      try {
        const ok = await connectUserToVoice(acc.token, guildId, channelId);
        results.push({ success: ok, username: acc.username });
      } catch (e) {
        results.push({ success: false, username: acc.username, error: e.message });
      }
    }

    const successfulAccounts = results.filter(r => r.success);
    const failedAccounts = results.filter(r => !r.success);

    // Also connect Discord Bot (dragon556)
    let joinedBot = false;
    if (guildId && channelId) {
      joinedBot = await connectBotToVoice(guildId, channelId).catch(() => false);
    }

    const totalConnected = successfulAccounts.length + (joinedBot ? 1 : 0);
    console.log(`[SPY WEB] Multi-account join summary: ${successfulAccounts.length}/${userAccs.length} operative accounts + ${joinedBot ? 1 : 0} bot connected to VC ${channelId}: [${successfulAccounts.map(a => a.username).join(', ') || 'none'}]`);

    if (failedAccounts.length > 0) {
      const failedMsg = failedAccounts.map(f => `${f.username}: ${f.error}`).join('; ');
      socket.emit('account_token_error', {
        error: `Operative note: ${failedMsg}`
      });
    }

    socket.emit('join_progress', {
      connected: successfulAccounts.length,
      total: userAccs.length,
      botConnected: joinedBot
    });

    if (typeof callback === 'function') {
      callback({
        success: totalConnected > 0,
        connectedCount: totalConnected,
        operativeCount: successfulAccounts.length,
        totalCount: userAccs.length,
        joinedBot,
        accountNames: successfulAccounts.map(a => a.username),
        errors: failedAccounts.map(f => `${f.username}: ${f.error}`),
        error: totalConnected === 0 ? (failedAccounts.length > 0 ? failedAccounts.map(f => f.error).join('; ') : 'Could not connect to voice channel. Verify channel ID and permissions.') : null
      });
    }
  }

  socket.on('join_voice', handleJoinVoice);
  socket.on('bot_join_voice', handleJoinVoice);

  // 8. Leave Voice Channel — ALL ACCOUNTS LEAVE
  function handleLeaveVoice(callback) {
    console.log(`[SPY WEB] Disconnecting all accounts from voice channel for license [${socket.activeLicenseKey}]`);
    currentLoopTrack = null;

    if (activeBotPlayer) {
      try { activeBotPlayer.stop(); } catch (e) {}
    }
    if (activeBotConnection) {
      try { activeBotConnection.destroy(); } catch (e) {}
      activeBotConnection = null;
    }

    for (const [token, op] of activeOperatives.entries()) {
      try { op.player?.stop(); } catch (e) {}
      try { op.connection?.destroy(); } catch (e) {}
      if (op.client && op.client.ws && op.client.ws.shards) {
        try {
          op.client.ws.shards.first()?.send({
            op: 4,
            d: { guild_id: null, channel_id: null, self_mute: false, self_deaf: false }
          });
        } catch (e) {}
      }
    }
    activeOperatives.clear();

    const botClient = getBotClient();
    if (botClient && botClient.ws && botClient.ws.shards) {
      try {
        botClient.ws.shards.first()?.send({
          op: 4,
          d: { guild_id: null, channel_id: null, self_mute: false, self_deaf: false }
        });
      } catch (e) {}
    }

    if (typeof callback === 'function') callback({ success: true });
  }

