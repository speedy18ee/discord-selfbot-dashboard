// High-Speed In-Memory Static Cache with Automatic Gzip & ETag
const staticCache = new Map();

function getCachedFile(relPath, contentType, maxAge = 86400) {
  const absPath = path.join(__dirname, relPath);
  if (!fs.existsSync(absPath)) return null;
  const stat = fs.statSync(absPath);
  const etag = `"${stat.size}-${Math.floor(stat.mtimeMs)}"`;
  const cached = staticCache.get(relPath);
  if (cached && cached.etag === etag) return cached;

  const raw = fs.readFileSync(absPath);
  const compressible = contentType.includes('text') || contentType.includes('json') || contentType.includes('javascript') || contentType.includes('svg');
  const gzipped = compressible ? zlib.gzipSync(raw, { level: 6 }) : null;

  const entry = {
    content: raw,
    gzipped,
    contentType,
    etag,
    maxAge
  };
  staticCache.set(relPath, entry);
  return entry;
}

const server = http.createServer((req, res) => {
  const urlPath = req.url.split('?')[0];

  // Resolve static file or SPA fallback
  let relPath = urlPath === '/' ? 'index.html' : urlPath.replace(/^\/+/, '');
  let absPath = path.join(__dirname, relPath);

  if (!fs.existsSync(absPath) || fs.statSync(absPath).isDirectory()) {
    relPath = 'index.html';
    absPath = path.join(__dirname, 'index.html');
  }

  const ext = path.extname(absPath).toLowerCase();
  const contentType = mimeTypes[ext] || 'application/octet-stream';
  const isHtml = ext === '.html';
  const maxAge = isHtml ? 120 : 604800; // 2 min for HTML, 7 days for static assets

  const file = getCachedFile(relPath, contentType, maxAge);
  if (!file) {
    res.writeHead(404, { 'Content-Type': 'text/plain' });
    return res.end('Not found');
  }

  // 304 Not Modified support
  if (req.headers['if-none-match'] === file.etag) {
    res.writeHead(304, {
      'ETag': file.etag,
      'Cache-Control': isHtml ? 'public, max-age=120, stale-while-revalidate=600' : 'public, max-age=604800, immutable'
    });
    return res.end();
  }

  const acceptEncoding = req.headers['accept-encoding'] || '';
  const canGzip = file.gzipped && acceptEncoding.includes('gzip');

  const headers = {
    'Content-Type': file.contentType,
    'ETag': file.etag,
    'Cache-Control': isHtml ? 'public, max-age=120, stale-while-revalidate=600' : 'public, max-age=604800, immutable',
    'Vary': 'Accept-Encoding'
  };

  if (canGzip) {
    headers['Content-Encoding'] = 'gzip';
    res.writeHead(200, headers);
    res.end(file.gzipped);
  } else {
    headers['Content-Length'] = file.content.length;
    res.writeHead(200, headers);
    res.end(file.content);
  }
});

